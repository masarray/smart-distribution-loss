import process from "node:process";
import { chromium } from "playwright";

const baseUrl = process.env.SDL_BASE_URL || "http://127.0.0.1:8000/";
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });

async function assertVisible(locator, label) {
  await locator.waitFor({ state: "visible", timeout: 15_000 });
  if (!(await locator.isVisible())) throw new Error(`${label} is not visible.`);
}

async function assertNoVisibleText(text, label) {
  const matches = page.getByText(text, { exact: false });
  for (let index = 0; index < await matches.count(); index += 1) {
    if (await matches.nth(index).isVisible()) throw new Error(`${label}: ${text}`);
  }
}

async function openSelectedAssetData() {
  await page.getByRole("button", { name: "Data", exact: true }).click();
}

try {
  await page.goto(baseUrl, { waitUntil: "domcontentloaded", timeout: 60_000 });

  await page.getByRole("button", { name: "Penyulang 20 kV", exact: true }).click();
  if ((await page.getByText("Data · Penyulang 20 kV", { exact: true }).count()) !== 0) {
    throw new Error("Asset navigation must not auto-open the Data drawer.");
  }
  await assertVisible(page.getByText("Penyulang 20 kV — total", { exact: true }), "selected Penyulang 20 kV view");

  await openSelectedAssetData();
  await assertVisible(page.getByText("Data · Penyulang 20 kV", { exact: true }), "Penyulang 20 kV data drawer title");
  await assertVisible(page.getByText("DEMO SINTETIS", { exact: true }).last(), "localized demo badge");

  for (const tab of ["Ringkasan", "Pengukuran", "Jaringan", "Hasil", "Jejak data"]) {
    await assertVisible(page.getByRole("tab", { name: tab, exact: true }), `${tab} tab`);
  }

  for (const internalTerm of ["Scenario ID", "Fingerprint", "Source kind", "Generated by", "Truth policy", "p1_ground_truth.py", "runpp_3ph"]) {
    await assertNoVisibleText(internalTerm, "Internal terminology leaked into Data drawer");
  }

  await page.getByRole("tab", { name: "Hasil", exact: true }).click();
  await assertVisible(page.getByText(/Jalankan simulasi untuk melihat 96 interval hasil/), "pre-run processed-data guidance");

  await page.getByRole("button", { name: "Close" }).click();
  await page.getByRole("button", { name: "Pelanggan TM", exact: true }).click();
  if ((await page.getByText("Data · Pelanggan TM", { exact: true }).count()) !== 0) {
    throw new Error("Pelanggan TM selection auto-opened the Data drawer.");
  }
  await openSelectedAssetData();
  await assertVisible(page.getByText("Data · Pelanggan TM", { exact: true }), "Pelanggan TM explicit drawer title");

  await page.getByRole("button", { name: "Close" }).click();
  await page.getByRole("button", { name: "Gardu GD-01", exact: true }).first().click();
  if ((await page.getByText("Data · Gardu GD-01", { exact: true }).count()) !== 0) {
    throw new Error("GD-01 selection auto-opened the Data drawer.");
  }
  await openSelectedAssetData();
  await assertVisible(page.getByText("Data · Gardu GD-01", { exact: true }), "GD-01 explicit drawer title");
  await page.getByRole("tab", { name: "Pengukuran", exact: true }).click();
  const gdDrawer = page.getByRole("dialog", { name: /Data · Gardu GD-01/ });
  await assertVisible(gdDrawer.getByText("Meter tersedia", { exact: true }), "GD-01 meter coverage");
  await assertVisible(gdDrawer.getByText("54/90", { exact: false }), "Poor-preset meter count");

  console.log("Data Drawer gate PASS: navigation stays unobstructed and all user-facing data language is localized.");
} finally {
  await browser.close();
}
